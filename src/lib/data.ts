const productsById = new Map(products.map((p) => [p.id, p]));
const productsBySlug = new Map(products.map((p) => [p.slug, p]));
const productsByBrandId = products.reduce((map, p) => {
  const list = map.get(p.brandId);
  if (list) list.push(p);
  else map.set(p.brandId, [p]);
  return map;
}, new Map<string, Product[]>());

export function getProduct(idOrSlug: string) {
  return productsById.get(idOrSlug) ?? productsBySlug.get(idOrSlug);
}

export function productsForBrand(brandId: string) {
  return productsByBrandId.get(brandId) ?? [];
}

export function reviewsForProduct(productId: string) {
  return reviews.filter((r) => r.productId === productId);
}

export function reviewsForBrand(brandId: string) {
  return reviews.filter((r) => r.brandId === brandId);
}

export function productsWithImages() {
  return products.filter((p) => p.imageUrl);
}

export function coverProductForBrand(brandId: string) {
  return products.find((p) => p.brandId === brandId && p.imageUrl);
}

export function coverProductForCategory(categoryId: string) {
  return products.find((p) => p.category === categoryId && p.imageUrl);
}

export function searchByIngredient(query: string, mode: "contains" | "free-from" = "contains") {
  const q = query.trim().toLowerCase();
  if (!q) return products;
  if (mode === "free-from") {
    return products.filter(
      (p) =>
        p.freeFrom.some((i) => i.toLowerCase().includes(q)) ||
        !p.ingredients.some((i) => i.toLowerCase().includes(q)),
    );
  }
  return products.filter(
    (p) =>
      p.ingredients.some((i) => i.toLowerCase().includes(q)) ||
      p.name.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q),
  );
}
