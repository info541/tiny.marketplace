/** @type {{name:string, domain:string, hint:string}[]} */
const CANDIDATES = [];

function add(name, domain, hint) {
  domain = String(domain)
    .toLowerCase()
    .replace(/^https?:\/\//, "")
    .replace(/^www\./, "")
    .replace(/\/.*$/, "")
    .trim();
  if (!domain || !domain.includes(".")) return;
  CANDIDATES.push({ name, domain, hint });
}

